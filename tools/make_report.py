h1("2. Background")
h2("2.1 System calls in xv6")
p("A user program calls a stub generated by <code>user/usys.pl</code>, which puts the system-call "
  "number in register <code>a7</code> and executes <code>ecall</code>. The trap goes through "
  "<code>trampoline.S</code> to <code>usertrap()</code>, which calls <code>syscall()</code>. That "
  "function looks up <code>syscalls[a7]</code>, runs the handler, and stores the return value in "
  "the saved <code>a0</code> of the trapframe. A single hook in <code>syscall()</code> therefore "
  "sees every system call and its result, which makes it the right place for the tracer.")
h2("2.2 Scheduling in xv6")
p("Each CPU runs <code>scheduler()</code>, which loops over the process table and "
  "<code>swtch()</code>es to the next RUNNABLE process. A timer interrupt fires every tick and "
  "<code>usertrap()</code>/<code>kerneltrap()</code> call <code>yield()</code>, so stock xv6 is a "
  "<b>round-robin scheduler with a 1-tick quantum</b>. It has no notion of priority. An "
  "interactive process that wakes up has to wait behind every CPU-bound process ahead of it in "
  "the table.")
h2("2.3 Multilevel Feedback Queue")
p("MLFQ (Corbató, CTSS 1962; described in OSTEP ch. 8) learns a process's behaviour from its "
  "past. It approximates <i>shortest-job-first</i> without knowing job lengths, and it gives "
  "interactive jobs good response time. The rules implemented here are:")
bl(["<b>Rule 1/2:</b> the highest-priority non-empty queue runs first; round-robin within a queue.",
    "<b>Rule 3:</b> a new process enters the top queue (Q0).",
    "<b>Rule 4:</b> a process that uses its whole time slice is demoted one level. A process that "
    "blocks before the slice ends stays at the same level.",
    "<b>Rule 5:</b> every <i>S</i> ticks all processes are boosted back to Q0 to prevent "
    "starvation.",
    "<b>Preemption:</b> when a higher-priority process becomes RUNNABLE, the running "
    "lower-priority process gives up the CPU."])

