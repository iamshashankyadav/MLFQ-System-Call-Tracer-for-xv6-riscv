def build_pdf():
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import cm
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.enums import TA_CENTER
    from reportlab.platypus import (BaseDocTemplate, PageTemplate, Frame, Paragraph, Spacer,
                                    Image, Table, TableStyle, PageBreak, Preformatted,
                                    KeepTogether, ListFlowable, ListItem)
    from PIL import Image as PILImage

    ss = getSampleStyleSheet()
    ink = colors.HexColor("#1b1b1b")
    accent = colors.HexColor("#1d5aa8")
    body = ParagraphStyle("body", parent=ss["BodyText"], fontName="Times-Roman", fontSize=11,
                          leading=15, textColor=ink, spaceAfter=6, alignment=4)
    H1 = ParagraphStyle("h1", parent=ss["Heading1"], fontName="Helvetica-Bold", fontSize=15,
                        textColor=accent, spaceBefore=12, spaceAfter=6)
    H2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold", fontSize=12,
                        textColor=ink, spaceBefore=8, spaceAfter=4)
    cap = ParagraphStyle("cap", parent=body, fontSize=9.5, alignment=TA_CENTER,
                         textColor=colors.HexColor("#52514e"), spaceBefore=2, spaceAfter=10)
    codest = ParagraphStyle("code", fontName="Courier", fontSize=8.2, leading=10,
                            textColor=ink, backColor=colors.HexColor("#f4f4f1"),
                            borderPadding=6, spaceBefore=4, spaceAfter=10, leftIndent=6,
                            rightIndent=6)
    cell = ParagraphStyle("cell", parent=body, fontSize=9.5, leading=12, alignment=0,
                          spaceAfter=0)
    cellb = ParagraphStyle("cellb", parent=cell, fontName="Times-Bold", textColor=colors.white)

    def mk(t):
        t = re.sub(r"<code>(.*?)</code>", r'<font face="Courier" size="9.5">\1</font>', t)
        return t

    def footer(canv, doc):
        canv.saveState()
        canv.setFont("Helvetica", 8.5)
        canv.setFillColor(colors.HexColor("#8a8984"))
        if doc.page > 1:
            canv.drawString(2 * cm, 1.2 * cm, f"{COURSE}  ·  MLFQ Scheduler + Syscall Tracer")
            canv.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"{STUDENT} ({ROLL})  ·  {doc.page}")
        canv.restoreState()

    doc = BaseDocTemplate(OUTPDF, pagesize=A4, leftMargin=2.2 * cm, rightMargin=2.2 * cm,
                          topMargin=2 * cm, bottomMargin=2 * cm,
                          title="MLFQ Scheduler + Syscall Tracer for xv6-riscv",
                          author=STUDENT)
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="f")
    doc.addPageTemplates([PageTemplate(id="p", frames=[frame], onPage=footer)])

    story = []
    # cover
    story += [Spacer(1, 3 * cm),
              Paragraph(COURSE, ParagraphStyle("c1", parent=H2, alignment=TA_CENTER,
                                               textColor=colors.HexColor("#52514e"))),
              Paragraph("Course Project Report", ParagraphStyle("c2", parent=body,
                        alignment=TA_CENTER, fontSize=13)),
              Spacer(1, 1.2 * cm),
              Paragraph("MLFQ Scheduler + System Call Tracer<br/>for xv6-riscv",
                        ParagraphStyle("t", parent=H1, fontSize=24, leading=30,
                                       alignment=TA_CENTER)),
              Spacer(1, 0.6 * cm),
              Paragraph("Using system-call tracing to evaluate a multilevel feedback queue "
                        "scheduler", ParagraphStyle("st", parent=body, alignment=TA_CENTER,
                                                    fontSize=12, textColor=colors.HexColor("#52514e"))),
              Spacer(1, 1.2 * cm)]
    story.append(Spacer(1, 1.5 * cm))
    info = Table([["Student name", STUDENT], ["Roll number", ROLL],
                  ["Course", COURSE], ["Platform", "xv6-riscv on QEMU (riscv64)"],
                  ["Date", datetime.date.today().strftime("%d %B %Y")]],
                 colWidths=[4 * cm, 8 * cm])
    info.setStyle(TableStyle([("FONT", (0, 0), (0, -1), "Helvetica-Bold", 10.5),
                              ("FONT", (1, 0), (1, -1), "Helvetica", 10.5),
                              ("LINEBELOW", (0, 0), (-1, -1), 0.4, colors.HexColor("#e6e5e0")),
                              ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    story += [info, PageBreak()]

    # table of contents (static, section titles)
    story.append(Paragraph("Contents", H1))
    for b in C:
        if b[0] == "h1":
            story.append(Paragraph(b[1], ParagraphStyle("toc", parent=body, fontSize=11.5,
                                                        spaceAfter=3)))
        elif b[0] == "h2":
            story.append(Paragraph("&nbsp;&nbsp;&nbsp;&nbsp;" + b[1],
                                   ParagraphStyle("toc2", parent=body, fontSize=10.5,
                                                  spaceAfter=1, textColor=colors.HexColor("#52514e"))))
    story.append(PageBreak())

    pending_h = []
    for b in C:
        kind = b[0]
        if kind == "h1":
            pending_h = [Paragraph(b[1], H1)]
            continue
        if kind == "h2":
            pending_h.append(Paragraph(b[1], H2))
            continue
        if kind == "p":
            fl = [Paragraph(mk(b[1]), body)]
        elif kind == "bullets":
            fl = [ListFlowable([ListItem(Paragraph(mk(t), body), leftIndent=12) for t in b[1]],
                               bulletType="bullet", start="•", leftIndent=14)]
        elif kind == "code":
            fl = [Preformatted(b[1], codest)]
        elif kind == "img":
            path, caption, wcm = b[1], b[2], b[3]
            iw, ih = PILImage.open(path).size
            wid = min(wcm * cm, doc.width)
            hei = wid * ih / iw
            if hei > 19 * cm:
                hei = 19 * cm; wid = hei * iw / ih
            fl = [KeepTogether([Image(path, width=wid, height=hei), Paragraph(caption, cap)])]
        elif kind == "table":
            rows, widths = b[1], b[2]
            data = [[Paragraph(mk(c), cellb if i == 0 else cell) for c in r]
                    for i, r in enumerate(rows)]
            tw = [x * cm for x in widths] if widths else None
            t = Table(data, colWidths=tw, repeatRows=1)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), accent),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f6fa")]),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c9cfd8")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
            fl = [t, Spacer(1, 4)]
        elif kind == "pagebreak":
            fl = [PageBreak()]
        if pending_h:
            story.append(KeepTogether(pending_h + fl[:1]))
            story += fl[1:]
            pending_h = []
        else:
            story += fl
    doc.build(story)
    print("wrote", OUTPDF)


