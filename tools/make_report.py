def build_docx():
    import docx
    from docx.shared import Pt, Cm, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    d = docx.Document()
    sec = d.sections[0]
    sec.left_margin = sec.right_margin = Cm(2.2)
    st_ = d.styles["Normal"]; st_.font.name = "Times New Roman"; st_.font.size = Pt(11)

    def runs(par, text, size=None):
        text = (text.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
                .replace("&nbsp;", " "))
        for tok in re.split(r"(<b>.*?</b>|<i>.*?</i>|<code>.*?</code>)", text):
            if not tok:
                continue
            mm = re.match(r"<(b|i|code)>(.*)</\1>", tok, re.S)
            inner = re.sub(r"</?(b|i|code)>", "", mm.group(2) if mm else tok)
            r = par.add_run(inner)
            if size:
                r.font.size = Pt(size)
            if mm and mm.group(1) == "b":
                r.bold = True
            if mm and mm.group(1) == "i":
                r.italic = True
            if mm and mm.group(1) == "code":
                r.font.name = "Courier New"; r.font.size = Pt(9.5)

    def shade(cell_, hexcolor):
        tcPr = cell_._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), hexcolor)
        tcPr.append(shd)

    # cover
    for t, sz, bold in ((COURSE, 13, True), ("Course Project Report", 12, False),
                        ("", 12, False),
                        ("MLFQ Scheduler + System Call Tracer for xv6-riscv", 22, True),
                        ("Using system-call tracing to evaluate a multilevel feedback queue "
                         "scheduler", 12, False)):
        par = d.add_paragraph(); par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = par.add_run(t); r.font.size = Pt(sz); r.bold = bold
    tb = d.add_table(rows=0, cols=2); tb.style = "Light List"
    for k, v in (("Student name", STUDENT), ("Roll number", ROLL), ("Course", COURSE),
                 ("Platform", "xv6-riscv on QEMU (riscv64)"),
                 ("Date", datetime.date.today().strftime("%d %B %Y"))):
        c = tb.add_row().cells; c[0].text = k; c[1].text = v
        c[0].paragraphs[0].runs[0].bold = True
    d.add_page_break()

    for b in C:
        kind = b[0]
        if kind == "h1":
            d.add_heading(b[1], level=1)
        elif kind == "h2":
            d.add_heading(b[1], level=2)
        elif kind == "p":
            runs(d.add_paragraph(), b[1])
        elif kind == "bullets":
            for t in b[1]:
                runs(d.add_paragraph(style="List Bullet"), t)
        elif kind == "code":
            par = d.add_paragraph()
            r = par.add_run(b[1]); r.font.name = "Courier New"; r.font.size = Pt(8)
            pPr = par._p.get_or_add_pPr()
            shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear")
            shd.set(qn("w:fill"), "F4F4F1"); pPr.append(shd)
        elif kind == "img":
            d.add_picture(b[1], width=Cm(min(b[3], 16.5)))
            d.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
            par = d.add_paragraph(); par.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = par.add_run(b[2]); r.italic = True; r.font.size = Pt(9.5)
        elif kind == "table":
            rows = b[1]
            t = d.add_table(rows=len(rows), cols=len(rows[0])); t.style = "Table Grid"
            for i, row in enumerate(rows):
                for j, val in enumerate(row):
                    cl = t.cell(i, j); cl.text = ""
                    runs(cl.paragraphs[0], val, size=9.5)
                    if i == 0:
                        shade(cl, "1D5AA8")
                        for r in cl.paragraphs[0].runs:
                            r.bold = True; r.font.color.rgb = RGBColor(255, 255, 255)
            d.add_paragraph()
        elif kind == "pagebreak":
            d.add_page_break()
    d.save(OUTDOCX)
    print("wrote", OUTDOCX)


if __name__ == "__main__":
    build_pdf()
    build_docx()
